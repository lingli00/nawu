/**
 * 灰占位图标专项补采（v1.0.32）。
 * 对人工核验出的 14 个灰占位域名换源重采：
 * ① 国内 favicon 接口（iowen / cccyun / byi）
 * ② 同品牌别名域名（netease→163、vip.zhihu→zhihu、amazon.cn→amazon、kdocs→www.kdocs）
 * ③ simple-icons 兜底（矢量 SVG，品牌色）
 * 运行：node _fix_placeholders.cjs
 */
const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, 'public', 'brand-icons');

/* domain -> 别名（同品牌，用别名的图标落库到本域名） */
const ALIAS = {
  'netease.com': '163.com',
  'vip.zhihu.com': 'zhihu.com',
  'amazon.cn': 'amazon.com',
  'kdocs.cn': 'www.kdocs.cn',
  'dianping.com': 'www.dianping.com',
  'ksyun.com': 'www.ksyun.com',
  '12306.cn': 'www.12306.cn',
};
/* simple-icons 兜底（slug） */
const SI = {
  'npmjs.com': 'npm',
  'amazon.cn': 'amazon',
  'cloud.google.com': 'googlecloud',
  '95516.com': 'unionpay',
  'vip.zhihu.com': 'zhihu',
};

const TARGETS = [
  'lazyaudio.com', 'ksyun.com', 'cloud.google.com', '12306.cn', '95516.com',
  'netease.com', 'dianping.com', 'vip.zhihu.com', 'hellohorse.com',
  'dengtedushu.com', 'izhen.com', 'kdocs.cn', 'amazon.cn', 'npmjs.com',
];

const MAGIC = [
  ['89504e47', 'png'], ['ffd8ff', 'jpg'], ['47494638', 'gif'],
  ['52494646', 'webp'], ['00000100', 'ico'], ['3c3f786d', 'svg'], ['3c737667', 'svg'],
];
function sniff(buf) {
  const hex = buf.subarray(0, 8).toString('hex');
  for (const [m, ext] of MAGIC) {
    if (hex.startsWith(m)) {
      if (ext === 'webp' && buf.subarray(8, 12).toString() !== 'WEBP') continue;
      return ext;
    }
  }
  return null;
}
async function fetchBin(url, timeoutMs = 12000) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: ac.signal, redirect: 'follow', headers: { 'User-Agent': 'Mozilla/5.0' } });
    if (!res.ok) return null;
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 150 || buf.length > 400000) return null;
    const ext = sniff(buf);
    if (!ext) return null;
    return { buf, ext };
  } catch {
    return null;
  } finally {
    clearTimeout(t);
  }
}

async function siSvg(slug) {
  try {
    const si = require('simple-icons');
    const key = 'si' + slug.charAt(0).toUpperCase() + slug.slice(1);
    const icon = si[key];
    if (!icon) return null;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${icon.path}" fill="#${icon.hex}"/></svg>`;
    return { buf: Buffer.from(svg, 'utf8'), ext: 'svg' };
  } catch {
    return null;
  }
}

function sourcesFor(d) {
  const list = [
    `https://api.iowen.cn/favicon/${d}.png`,
    `https://favicon.cccyun.cc/${d}`,
    `https://api.byi.pw/favicon/${d}`,
    `http://106.53.204.29/api/icon/img?d=${encodeURIComponent(d)}`,
  ];
  const alias = ALIAS[d];
  if (alias) {
    list.unshift(`http://106.53.204.29/api/icon/img?d=${encodeURIComponent(alias)}`);
    list.push(`https://${alias}/favicon.ico`);
  }
  return list;
}

(async () => {
  const still = [];
  for (const d of TARGETS) {
    let got = null;
    for (const url of sourcesFor(d)) {
      got = await fetchBin(url);
      if (got) break;
    }
    if (!got) got = await siSvg(SI[d]);
    if (got) {
      // 清掉旧占位文件（扩展名可能不同）
      for (const f of fs.readdirSync(OUT)) if (f.startsWith(d + '.')) fs.unlinkSync(path.join(OUT, f));
      const file = `${d}.${got.ext}`;
      fs.writeFileSync(path.join(OUT, file), got.buf);
      console.log('OK ', d, '->', file, got.buf.length + 'B');
    } else {
      still.push(d);
      console.log('MISS', d);
    }
  }
  // 重生成清单
  const assets = {};
  for (const f of fs.readdirSync(OUT)) assets[f.replace(/\.[a-z]+$/, '')] = `/brand-icons/${f}`;
  const lines = Object.keys(assets).sort().map((k) => `  '${k}': '${assets[k]}',`);
  const tsOut = `/* AUTO-GENERATED by _collect_brand_icons.cjs — v1.0.32 品牌图标资产清单。\n * domain → 打包进安装包/站点的站内路径（public/brand-icons/）。\n * 重新生成：node _collect_brand_icons.cjs [--force] */\n\nexport const BRAND_ICON_ASSETS: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
  fs.writeFileSync(path.join(__dirname, 'src', 'generated', 'brandIconAssets.ts'), tsOut, 'utf8');
  console.log('---');
  console.log(still.length ? 'STILL MISSING: ' + still.join(', ') : 'ALL FIXED');
})();
