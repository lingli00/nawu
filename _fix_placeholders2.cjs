const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, 'public', 'brand-icons');
const TARGETS = ['lazyaudio.com', 'ksyun.com', '12306.cn', '95516.com', 'dianping.com', 'hellohorse.com', 'dengtedushu.com', 'izhen.com', 'kdocs.cn'];

const MAGIC = [
  ['89504e47', 'png'], ['ffd8ff', 'jpg'], ['47494638', 'gif'],
  ['52494646', 'webp'], ['00000100', 'ico'], ['3c3f786d', 'svg'], ['3c737667', 'svg'],
];
function sniff(buf) {
  const hex = buf.subarray(0, 8).toString('hex');
  for (const [m, ext] of MAGIC) {
    if (hex.startsWith(m)) {
      if (ext === 'webp' && buf.subarray(8, 12).toString() !== 'WEBP') continue;
      return ext;
    }
  }
  return null;
}
async function fetchBin(url, timeoutMs = 12000) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: ac.signal, redirect: 'follow', headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/126 Safari/537.36' } });
    if (!res.ok) return null;
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 150 || buf.length > 600000) return null;
    const ext = sniff(buf);
    if (!ext) return null;
    return { buf, ext };
  } catch {
    return null;
  } finally {
    clearTimeout(t);
  }
}
async function fetchText(url, timeoutMs = 12000) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: ac.signal, redirect: 'follow', headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/126 Safari/537.36' } });
    if (!res.ok) return null;
    return await res.text();
  } catch {
    return null;
  } finally {
    clearTimeout(t);
  }
}
/** 从站点首页 HTML 解析 icon 候选直链。 */
function iconLinksFromHtml(html, baseUrl) {
  if (!html) return [];
  const out = [];
  const re = /<link[^>]+>/gi;
  let m;
  while ((m = re.exec(html))) {
    const tag = m[0];
    if (!/rel\s*=\s*["'][^"']*icon[^"']*["']/i.test(tag)) continue;
    const href = (tag.match(/href\s*=\s*["']([^"']+)["']/i) || [])[1];
    if (href) out.push(href);
  }
  const at = html.match(/<meta[^>]+property=["']og:image["'][^>]+content=["']([^"']+)["']/i);
  if (at) out.push(at[1]);
  return out
    .map((h) => {
      try {
        return new URL(h, baseUrl).href;
      } catch {
        return null;
      }
    })
    .filter(Boolean)
    .filter((u) => /^https?:/.test(u));
}
async function siSearch(kw) {
  try {
    const si = require('simple-icons');
    const hit = Object.entries(si).find(([k]) => k.toLowerCase().includes(kw));
    if (!hit) return null;
    const icon = hit[1];
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${icon.path}" fill="#${icon.hex}"/></svg>`;
    return { buf: Buffer.from(svg, 'utf8'), ext: 'svg' };
  } catch {
    return null;
  }
}

const SI_HINT = { '95516.com': 'union', 'kdocs.cn': 'wps', 'ksyun.com': 'kingsoft', 'dianping.com': 'dianping', '12306.cn': 'railway' };

(async () => {
  const still = [];
  for (const d of TARGETS) {
    let got = null;
    const urls = [
      `https://bpp.baidu.com/icon?url=${encodeURIComponent(d)}?size=64`,
      `https://api.zxki.cn/favicon/?url=${d}`,
      `https://favicon.51240.com/get.php?url=${d}`,
    ];
    for (const u of urls) {
      got = await fetchBin(u);
      if (got) { console.log(d, 'via api', u.slice(0, 60)); break; }
    }
    // 站点 HTML 解析（http/https × 裸域/www）
    if (!got) {
      for (const host of [d, 'www.' + d]) {
        for (const sch of ['https', 'http']) {
          if (got) break;
          const base = `${sch}://${host}/`;
          const html = await fetchText(base);
          for (const iconUrl of iconLinksFromHtml(html, base)) {
            got = await fetchBin(iconUrl);
            if (got) { console.log(d, 'via html', iconUrl.slice(0, 80)); break; }
          }
        }
        if (got) break;
      }
    }
    if (!got) got = await siSearch(SI_HINT[d] || d.split('.')[0]);
    if (got) {
      for (const f of fs.readdirSync(OUT)) if (f.startsWith(d + '.')) fs.unlinkSync(path.join(OUT, f));
      const file = `${d}.${got.ext}`;
      fs.writeFileSync(path.join(OUT, file), got.buf);
      console.log('OK ', d, '->', file, got.buf.length + 'B');
    } else {
      still.push(d);
      console.log('MISS', d);
    }
  }
  // 重生成清单
  const assets = {};
  for (const f of fs.readdirSync(OUT)) assets[f.replace(/\.[a-z]+$/, '')] = `/brand-icons/${f}`;
  const lines = Object.keys(assets).sort().map((k) => `  '${k}': '${assets[k]}',`);
  const tsOut = `/* AUTO-GENERATED by _collect_brand_icons.cjs — v1.0.32 品牌图标资产清单。\n * domain → 打包进安装包/站点的站内路径（public/brand-icons/）。\n * 重新生成：node _collect_brand_icons.cjs [--force] */\n\nexport const BRAND_ICON_ASSETS: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
  fs.writeFileSync(path.join(__dirname, 'src', 'generated', 'brandIconAssets.ts'), tsOut, 'utf8');
  console.log('---');
  console.log(still.length ? 'STILL: ' + still.join(', ') : 'ALL FIXED');
})();
