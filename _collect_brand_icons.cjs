/**
 * 品牌图标预采集脚本（v1.0.32）。
 * 把 BRAND_GROUPS 里所有域名的真实图标抓进 public/brand-icons/，
 * 生成 src/generated/brandIconAssets.ts（domain → 站内路径）。
 * 运行：node _collect_brand_icons.cjs [--force]
 */
const fs = require('fs');
const path = require('path');

const FORCE = process.argv.includes('--force');
const OUT_DIR = path.join(__dirname, 'public', 'brand-icons');
const GEN_TS = path.join(__dirname, 'src', 'generated', 'brandIconAssets.ts');
const SERVER = 'http://106.53.204.29';

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.mkdirSync(path.dirname(GEN_TS), { recursive: true });

/* 1. 从 brandIcon.ts 抠出全部域名 */
const ts = fs.readFileSync(path.join(__dirname, 'src', 'lib', 'brandIcon.ts'), 'utf8');
const domains = [...new Set([...ts.matchAll(/domain:\s*'([^']+)'/g)].map((m) => m[1]))].sort();
console.log('domains:', domains.length);

/* 2. 已有合法文件 → 跳过（--force 重抓） */
const MAGIC = [
  ['89504e47', 'png'], ['ffd8ff', 'jpg'], ['47494638', 'gif'],
  ['52494646', 'webp'], ['00000100', 'ico'], ['3c3f786d', 'svg'], ['3c737667', 'svg'],
];
function sniff(buf) {
  const hex = buf.subarray(0, 8).toString('hex');
  for (const [m, ext] of MAGIC) {
    if (hex.startsWith(m)) {
      // RIFF 需要再确认 WEBP
      if (ext === 'webp' && buf.subarray(8, 12).toString() !== 'WEBP') continue;
      return ext;
    }
  }
  return null;
}
function validFile(p) {
  try {
    const b = fs.readFileSync(p);
    return b.length > 100 && b.length < 400000 && sniff(b) !== null;
  } catch {
    return false;
  }
}

async function fetchBin(url, timeoutMs = 12000) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: ac.signal, redirect: 'follow', headers: { 'User-Agent': 'Mozilla/5.0 NaWuIconCollector/1.0' } });
    if (!res.ok) return null;
    const ct = (res.headers.get('content-type') || '').toLowerCase();
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 100 || buf.length > 400000) return null;
    const ext = sniff(buf);
    if (!ext) return null;
    if (ct && !ct.includes('image') && !ct.includes('octet-stream')) return null;
    return { buf, ext };
  } catch {
    return null;
  } finally {
    clearTimeout(t);
  }
}

function sourcesFor(d) {
  return [
    `${SERVER}/api/icon/img?d=${encodeURIComponent(d)}`,
    `https://icon.horse/icon/${d}`,
    `https://favicon.im/${d}?larger=true`,
    `https://www.google.com/s2/favicons?sz=64&domain=${d}`,
    `https://${d}/favicon.ico`,
    `https://www.${d}/favicon.ico`,
  ];
}

const assets = {}; // domain -> '/brand-icons/<file>'
const missing = [];
let cursor = 0;
const CONC = 8;

async function worker() {
  while (cursor < domains.length) {
    const d = domains[cursor++];
    // 命名安全化（域名本身即安全字符集）
    const existing = fs.readdirSync(OUT_DIR).find((f) => f.startsWith(d + '.'));
    if (!FORCE && existing && validFile(path.join(OUT_DIR, existing))) {
      assets[d] = `/brand-icons/${existing}`;
      continue;
    }
    let got = null;
    for (const url of sourcesFor(d)) {
      got = await fetchBin(url);
      if (got) break;
    }
    if (got) {
      const file = `${d}.${got.ext}`;
      fs.writeFileSync(path.join(OUT_DIR, file), got.buf);
      assets[d] = `/brand-icons/${file}`;
    } else {
      missing.push(d);
    }
  }
}

(async () => {
  const t0 = Date.now();
  await Promise.all(Array.from({ length: CONC }, worker));
  // 3. 生成清单 TS
  const lines = Object.keys(assets).sort().map((d) => `  '${d}': '${assets[d]}',`);
  const tsOut = `/* AUTO-GENERATED by _collect_brand_icons.cjs — v1.0.32 品牌图标资产清单。\n * domain → 打包进安装包/站点的站内路径（public/brand-icons/）。\n * 重新生成：node _collect_brand_icons.cjs [--force] */\n\nexport const BRAND_ICON_ASSETS: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
  fs.writeFileSync(GEN_TS, tsOut, 'utf8');
  fs.writeFileSync(path.join(__dirname, '_collect_report.json'), JSON.stringify({ ok: Object.keys(assets).length, missing, at: new Date().toISOString() }, null, 2));
  console.log(`done in ${((Date.now() - t0) / 1000).toFixed(0)}s — collected: ${Object.keys(assets).length}/${domains.length}`);
  if (missing.length) console.log('MISSING:', missing.join(', '));
})();
