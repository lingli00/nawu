const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, 'public', 'brand-icons');

const MAGIC = [
  ['89504e47', 'png'], ['ffd8ff', 'jpg'], ['47494638', 'gif'],
  ['52494646', 'webp'], ['00000100', 'ico'], ['3c3f786d', 'svg'], ['3c737667', 'svg'],
];
function sniff(buf) {
  const hex = buf.subarray(0, 8).toString('hex');
  for (const [m, ext] of MAGIC) {
    if (hex.startsWith(m)) {
      if (ext === 'webp' && buf.subarray(8, 12).toString() !== 'WEBP') continue;
      return ext;
    }
  }
  return null;
}
async function fetchBin(url, timeoutMs = 12000) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: ac.signal, redirect: 'follow', headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/126 Safari/537.36' } });
    if (!res.ok) return null;
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 150 || buf.length > 600000) return null;
    const ext = sniff(buf);
    if (!ext) return null;
    return { buf, ext };
  } catch {
    return null;
  } finally {
    clearTimeout(t);
  }
}
function siSvg(slug) {
  const si = require('simple-icons');
  const key = 'si' + slug.charAt(0).toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) return null;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${icon.path}" fill="#${icon.hex}"/></svg>`;
  return { buf: Buffer.from(svg, 'utf8'), ext: 'svg' };
}
/** 品牌色圆角字母牌（确定性配色）。 */
function letterTile(domain) {
  const PALETTE = ['#2E7D32', '#1565C0', '#6A1B9A', '#C62828', '#00838F', '#EF6C00', '#4527A0', '#37474F'];
  let h = 0;
  for (const ch of domain) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  const color = PALETTE[h % PALETTE.length];
  const letter = domain.replace(/^www\./, '').charAt(0).toUpperCase();
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="${color}"/><text x="32" y="44" font-family="Arial, sans-serif" font-size="34" font-weight="700" fill="#ffffff" text-anchor="middle">${letter}</text></svg>`;
  return { buf: Buffer.from(svg, 'utf8'), ext: 'svg' };
}
function save(d, got) {
  for (const f of fs.readdirSync(OUT)) if (f.startsWith(d + '.')) fs.unlinkSync(path.join(OUT, f));
  const file = `${d}.${got.ext}`;
  fs.writeFileSync(path.join(OUT, file), got.buf);
  console.log('OK ', d, '->', file, got.buf.length + 'B');
}

(async () => {
  /* ① slug 修正 */
  save('12306.cn', siSvg('chinarailway'));
  save('dianping.com', siSvg('dazhongdianping'));

  /* ② 别名域名试采 */
  for (const [d, aliases] of Object.entries({
    '95516.com': ['chinaunionpay.com', 'www.chinaunionpay.com', 'unionpay.com'],
    'kdocs.cn': ['www.wps.cn', 'wps.cn', 'ksosoft.com'],
    'lazyaudio.com': ['www.lazyaudio.com', 'lazyaudio.cn'],
    'hellohorse.com': ['www.hellohorse.com'],
    'dengtedushu.com': ['www.dengtedushu.com'],
    'izhen.com': ['www.izhen.com'],
  })) {
    let got = null;
    for (const a of aliases) {
      for (const u of [
        `http://106.53.204.29/api/icon/img?d=${encodeURIComponent(a)}`,
        `https://bpp.baidu.com/icon?url=${encodeURIComponent(a)}?size=64`,
      ]) {
        got = await fetchBin(u);
        if (got) { console.log(d, 'via', a); break; }
      }
      if (got) break;
    }
    if (got) save(d, got);
    else { save(d, letterTile(d)); console.log('FALLBACK letter tile:', d); }
  }

  /* 重生成清单 */
  const assets = {};
  for (const f of fs.readdirSync(OUT)) assets[f.replace(/\.[a-z]+$/, '')] = `/brand-icons/${f}`;
  const lines = Object.keys(assets).sort().map((k) => `  '${k}': '${assets[k]}',`);
  const tsOut = `/* AUTO-GENERATED by _collect_brand_icons.cjs — v1.0.32 品牌图标资产清单。\n * domain → 打包进安装包/站点的站内路径（public/brand-icons/）。\n * 重新生成：node _collect_brand_icons.cjs [--force] */\n\nexport const BRAND_ICON_ASSETS: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
  fs.writeFileSync(path.join(__dirname, 'src', 'generated', 'brandIconAssets.ts'), tsOut, 'utf8');
  console.log('manifest entries:', Object.keys(assets).length);
})();
